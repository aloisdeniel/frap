pub fn generate(probe_root: &Path) -> Output {
    let dumps = probe_root.join("dumps");
    let mut stats = Stats::default();
    let mut files = BTreeMap::new();

    let rna_meta = read_json(&dumps.join("rna/_meta.json"));
    files.insert(probe_root.join("rna/src/generated/enums.rs"), gen_enums(&rna_meta));
    files.insert(probe_root.join("rna/src/generated/mod.rs"), format!("{HEADER}pub mod enums;\n"));

    let mut structs = BTreeMap::new();
    for name in rna_meta["structs"].as_array().unwrap() {
        let n = name.as_str().unwrap();
        structs.insert(n.to_string(), read_json(&dumps.join(format!("rna/{n}.json"))));
    }
    let mut rna_mod = String::from(HEADER);
    let mut all_structs = vec![];
    let mut const_names: BTreeMap<String, String> = BTreeMap::new();
    for (n, d) in &structs {
        for p in d["props"].as_array().unwrap() {
            let pid = p["identifier"].as_str().unwrap();
            let c = format!("{}_{}", screaming(n), screaming_prop(pid));
            if let Some(prev) = const_names.insert(c.clone(), format!("{n}.{pid}")) {
                stats.const_name_collisions.push(format!("{c}: {prev} vs {n}.{pid}"));
            }
        }
    }
    for (n, d) in &structs {
        let m = snake(n);
        files.insert(
            probe_root.join(format!("spec/src/generated/rna/{m}.rs")),
            gen_struct(d, &structs, &mut stats),
        );
        let _ = writeln!(rna_mod, "pub mod {m};\npub use {m}::*;");
        all_structs.push(format!("&{m}::{}", screaming(n)));
    }
    let _ = writeln!(
        rna_mod,
        "\npub static ALL: [&frap_probe_rna::def::StructDef; {}] = [{}];",
        all_structs.len(),
        all_structs.join(", ")
    );
    files.insert(probe_root.join("spec/src/generated/rna/mod.rs"), rna_mod);

    let ops_meta = read_json(&dumps.join("ops/_meta.json"));
    let mut ops_mod = String::from(HEADER);
    for ns in ops_meta["namespaces"].as_array().unwrap() {
        let ns = ns.as_str().unwrap();
        let d = read_json(&dumps.join(format!("ops/{ns}.json")));
        files.insert(
            probe_root.join(format!("spec/src/generated/ops/{ns}.rs")),
            gen_ops(ns, &d, &mut stats),
        );
        let _ = writeln!(ops_mod, "pub mod {ns};");
    }
    files.insert(probe_root.join("spec/src/generated/ops/mod.rs"), ops_mod);
    files.insert(
        probe_root.join("spec/src/generated/mod.rs"),
        format!("{HEADER}pub mod ops;\npub mod rna;\n"),
    );
    Output { files, stats }
}

/// Files that differ from disk (drift check, §4.2 `--check`).
pub fn drift(out: &Output) -> Vec<PathBuf> {
    out.files
        .iter()
        .filter(|(p, s)| std::fs::read_to_string(p).ok().as_deref() != Some(s.as_str()))
        .map(|(p, _)| p.clone())
        .collect()
}

pub fn probe_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap().to_path_buf()
}

