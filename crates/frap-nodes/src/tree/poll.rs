//! `nodes.new` poll failures for node types of another tree type (WP 1.11).
//!
//! Blender 5.2.4 answers `nodes.new(type)` for a registered node type whose `poll` rejects
//! the tree with `RuntimeError: Error: Cannot add node of type <type> to node tree
//! '<tree name>'\n  <poll message>\n` (verified: `GeometryNodeMeshCube` on a material tree
//! gives `Not a geometry node tree`). Unregistered names still give `Node type … undefined`.
//! frap stores the message without the trailing newline, like every other report it raises
//! (the golden comparison normalises whitespace).
//!
//! The tables below list every registered node type of Blender 5.2.4 that a shader tree
//! rejects ([`FOREIGN_NODE_TYPES`], with its poll message) and every type of the generated
//! shader table that a geometry tree rejects ([`SHADER_ONLY_NODE_TYPES`]). Dumped on 5.2.4
//! (`--factory-startup`) by calling `nodes.new` for every `bpy.types.Node` subclass on a
//! material tree and on a `GeometryNodeTree` group and keeping the poll failures. The eight
//! function/geometry nodes that shader trees accept (`FunctionNodeInputBool`,
//! `GeometryNodeRepeatInput`, …) are not in the generated table yet and still answer
//! `undefined` (deviations.md).

use frap_rna::{PyExc, RnaError, RnaErrorKind};

use crate::{NodeTree, NodeTreeType};

/// The poll message of a node type that a tree type rejects.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub(crate) enum Poll {
    /// `Not a geometry node tree`
    Geometry,
    /// `Not a compositor node tree`
    Compositor,
    /// `Not a geometry or compositor node tree`
    GeometryOrCompositor,
    /// `Not a texture node tree`
    Texture,
    /// `Not a shader node tree`
    Shader,
}

impl Poll {
    fn message(self) -> &'static str {
        match self {
            Poll::Geometry => "Not a geometry node tree",
            Poll::Compositor => "Not a compositor node tree",
            Poll::GeometryOrCompositor => "Not a geometry or compositor node tree",
            Poll::Texture => "Not a texture node tree",
            Poll::Shader => "Not a shader node tree",
        }
    }
}

/// The poll failure of adding a node of type `bl_idname` to a tree of type `ty`, if
/// Blender has that type and the tree rejects it.
pub(crate) fn poll_failure(ty: NodeTreeType, bl_idname: &str) -> Option<Poll> {
    match ty {
        NodeTreeType::Shader => FOREIGN_NODE_TYPES
            .binary_search_by(|(n, _)| (*n).cmp(bl_idname))
            .ok()
            .map(|i| FOREIGN_NODE_TYPES[i].1),
        _ => SHADER_ONLY_NODE_TYPES
            .binary_search(&bl_idname)
            .is_ok()
            .then_some(Poll::Shader),
    }
}

/// `RuntimeError: Error: Cannot add node of type <type> to node tree '<tree>'\n  <poll>`.
pub(crate) fn poll_error(tree: &NodeTree, bl_idname: &str, poll: Poll) -> RnaError {
    RnaError::new(
        RnaErrorKind::Other,
        PyExc::RuntimeError,
        format!(
            "Error: Cannot add node of type {bl_idname} to node tree '{}'\n  {}",
            tree.header.name,
            poll.message()
        ),
    )
}

