const DEFAULT_DESC: &str = "Input value used for unconnected socket";

// Blender fills `NodeTreeInterfaceSocket.socket_type` from a callback that depends on the tree
// type (`rna_NodeTreeInterfaceSocket_socket_type_itemf`); the generated property lists only the
// class-level placeholder 'DEFAULT', so coercion would refuse every real type. Each typed item
// struct therefore exists once per tree type, listing first a `socket_type` with that tree
// type's items (so `find_prop` finds it before the base's, and an invalid write gets Blender's
// exact `TypeError` list). Writes go through the `NodeTreeInterfaceSocket.socket_type` hook
// (frap-ops-data), which also refreshes the group nodes.

const fn socket_type(items: &'static [EnumItem]) -> PropDef {
    PropDef {
        identifier: "socket_type",
        name: "Socket Type",
        description: "Type of the socket generated by this interface item",
        kind: PropKind::Enum {
            items,
            default: EnumDefault::Item("DEFAULT"),
            dynamic: None,
        },
        subtype: Subtype::None,
        unit: Unit::None,
        array: ArrayShape::Scalar,
        flags: PropFlags::empty(),
        deprecated: None,
    }
}

