/// The socket type an interface item of a tree of type `tree` takes for `socket_type` (an item
/// of the RNA items), or Blender's `TypeError` when the tree type does not list it
/// (`prefix` is the caller's: an assignment or a `new_socket` argument; verified on 5.2.4), or
/// `NotImplementedError` for a class frap cannot store as an interface item yet.
pub fn socket_type_of(
    tree: crate::NodeTreeType,
    socket_type: &str,
    prefix: &str,
) -> Result<SocketType, RnaError> {
    let valid = crate::interface_socket_types(tree);
    if !valid.contains(&socket_type) {
        let listed = valid
            .iter()
            .map(|n| format!("'{n}'"))
            .collect::<Vec<_>>()
            .join(", ");
        return Err(RnaError::new(
            RnaErrorKind::Enum,
            PyExc::TypeError,
            format!("{prefix}enum \"{socket_type}\" not found in ({listed})"),
        )
        .with_detail("valid", valid.to_vec()));
    }
    crate::interface_socket_type(socket_type).ok_or_else(|| {
        RnaError::new(
            RnaErrorKind::NotImplemented,
            PyExc::NotImplementedError,
            format!("frap: interface sockets of type {socket_type} are not implemented yet"),
        )
    })
}

/// Prefix of Blender's errors for an assignment (`item.socket_type = …`).
pub const SET_PREFIX: &str = "bpy_struct: item.attr = val: ";

/// The RNA struct of an interface item of type `ty` in a tree of type `tree`.
pub fn item_srna(tree: crate::NodeTreeType, ty: SocketType) -> &'static StructDef {
    let geometry = tree == crate::NodeTreeType::Geometry;
    let (sh, geo) = match ty {
        SocketType::Value => (
            &NODE_TREE_INTERFACE_SOCKET_FLOAT,
            &GEOMETRY_INTERFACE_SOCKET_FLOAT,
        ),
        SocketType::Int => (
            &NODE_TREE_INTERFACE_SOCKET_INT,
            &GEOMETRY_INTERFACE_SOCKET_INT,
        ),
        SocketType::Boolean => (
            &NODE_TREE_INTERFACE_SOCKET_BOOL,
            &GEOMETRY_INTERFACE_SOCKET_BOOL,
        ),
        SocketType::Vector => (
            &NODE_TREE_INTERFACE_SOCKET_VECTOR,
            &GEOMETRY_INTERFACE_SOCKET_VECTOR,
        ),
        SocketType::Rgba => (
            &NODE_TREE_INTERFACE_SOCKET_COLOR,
            &GEOMETRY_INTERFACE_SOCKET_COLOR,
        ),
        SocketType::Shader => (
            &NODE_TREE_INTERFACE_SOCKET_SHADER,
            &GEOMETRY_INTERFACE_SOCKET_SHADER,
        ),
        SocketType::Menu => (
            &NODE_TREE_INTERFACE_SOCKET_MENU,
            &GEOMETRY_INTERFACE_SOCKET_MENU,
        ),
        SocketType::Geometry => (
            &SHADER_INTERFACE_SOCKET_GEOMETRY,
            &NODE_TREE_INTERFACE_SOCKET_GEOMETRY,
        ),
        _ => return &frap_spec_rna::NODE_TREE_INTERFACE_SOCKET,
    };
    if geometry { geo } else { sh }
}

/// The index of the interface item a pointer path ends on (`…interface.items_tree[i]` or
/// `…interface.items_tree['Name']`), for hooks and RNA functions.
pub fn item_index_of(t: &NodeTree, path: &[Seg]) -> Option<usize> {
    match path {
        [.., Seg::Prop("interface"), Seg::Prop("items_tree"), seg] => match seg {
            Seg::Index(i) => usize::try_from(*i).ok().filter(|i| *i < t.interface.len()),
            Seg::Key(k) => t.interface.iter().position(|s| s.name == k.as_str()),
            Seg::Prop(_) => None,
        },
        _ => None,
    }
}

