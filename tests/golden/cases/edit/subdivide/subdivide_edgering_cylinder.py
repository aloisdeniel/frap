# WP 2.6: mesh.subdivide_edgering between the closed rims of cylinders (the n-gon caps stay out):
# PATH with smoothness and a profile, SURFACE, LINEAR with a profile; loop cuts across the ring.
# golden: startup=factory compare=objects,mesh:Cylinder,mesh:Cylinder.001,mesh:Cylinder.002,mesh:Cylinder.003 tier=T1
import bpy
bpy.ops.mesh.primitive_cylinder_add(vertices=8)
bpy.ops.object.mode_set(mode='EDIT')
bpy.ops.mesh.select_mode(type='EDGE')
bpy.ops.mesh.select_all(action='DESELECT')
bpy.ops.frap.select_elements(type='EDGE', indices=[2, 3, 6, 9, 12, 15, 18, 21])
bpy.ops.mesh.subdivide_edgering(number_cuts=4, smoothness=1.5, profile_shape_factor=-0.3, profile_shape='SMOOTH')
bpy.ops.object.mode_set(mode='OBJECT')
bpy.ops.mesh.primitive_cylinder_add(vertices=8, location=(3, 0, 0))
bpy.ops.object.mode_set(mode='EDIT')
bpy.ops.mesh.select_all(action='DESELECT')
bpy.ops.frap.select_elements(type='EDGE', indices=[2, 3, 6, 9, 12, 15, 18, 21])
bpy.ops.mesh.subdivide_edgering(number_cuts=3, interpolation='SURFACE', smoothness=0.8)
bpy.ops.object.mode_set(mode='OBJECT')
bpy.ops.mesh.primitive_cylinder_add(vertices=8, location=(-3, 0, 0))
bpy.ops.object.mode_set(mode='EDIT')
bpy.ops.mesh.select_all(action='DESELECT')
bpy.ops.frap.select_elements(type='EDGE', indices=[2, 3, 6, 9, 12, 15, 18, 21])
bpy.ops.mesh.subdivide_edgering(number_cuts=2, interpolation='LINEAR', profile_shape_factor=0.4, profile_shape='ROOT')
bpy.ops.object.mode_set(mode='OBJECT')
bpy.ops.mesh.primitive_cylinder_add(vertices=6, location=(0, 3, 0))
bpy.ops.object.mode_set(mode='EDIT')
bpy.ops.mesh.select_all(action='DESELECT')
bpy.ops.mesh.loopcut(number_cuts=2, edge_index=2, object_index=0)
bpy.ops.mesh.select_all(action='DESELECT')
bpy.ops.mesh.loopcut(number_cuts=1, edge_index=0, object_index=0)
