# WP 8.3.2: mesh.uvs_rotate / uvs_reverse move the active UV map's values around each selected
# face (clockwise, counter-clockwise, reversed; a second, active UV map; a triangle and an
# n-gon), mesh.colors_rotate / colors_reverse the active colour attribute's when it is a
# face-corner colour (FLOAT_COLOR and BYTE_COLOR; a point colour or no colour is left alone).
# golden: startup=factory compare=objects,context,mesh:Cube,mesh:Cylinder tier=T0
import bpy
bpy.ops.mesh.uvs_rotate()
bpy.ops.mesh.uv_texture_add()
bpy.ops.geometry.color_attribute_add(name='Pt', domain='POINT', color=(0.2, 0.4, 0.6, 1.0))
bpy.ops.object.mode_set(mode='EDIT')
bpy.ops.mesh.select_all(action='SELECT')
bpy.ops.mesh.colors_rotate()
bpy.ops.mesh.select_mode(type='FACE')
bpy.ops.frap.select_elements(type='FACE', indices=[0, 3])
bpy.ops.mesh.uvs_rotate()
bpy.ops.frap.select_elements(type='FACE', indices=[1, 3])
bpy.ops.mesh.uvs_rotate(use_ccw=True)
bpy.ops.frap.select_elements(type='FACE', indices=[2, 5])
bpy.ops.mesh.uvs_reverse()
bpy.ops.object.mode_set(mode='OBJECT')
bpy.ops.mesh.primitive_cylinder_add(vertices=7, location=(3, 0, 0))
bpy.ops.mesh.uv_texture_add()
bpy.ops.geometry.color_attribute_add(name='Fc', domain='CORNER', data_type='FLOAT_COLOR', color=(1.0, 1.0, 1.0, 1.0))
bpy.ops.geometry.color_attribute_add(name='Bc', domain='CORNER', data_type='BYTE_COLOR', color=(1.0, 1.0, 1.0, 1.0))
bpy.ops.object.mode_set(mode='EDIT')
bpy.ops.mesh.select_all(action='SELECT')
bpy.ops.mesh.quads_convert_to_tris()
bpy.ops.mesh.select_mode(type='FACE')
bpy.ops.frap.select_elements(type='FACE', indices=[0, 5, 14])
bpy.ops.mesh.uvs_rotate(use_ccw=True)
bpy.ops.mesh.uvs_reverse()
bpy.ops.object.mode_set(mode='OBJECT')
bpy.data.meshes['Cylinder'].attributes['Fc'].data[0].color = (0.1, 0.2, 0.3, 0.4)
bpy.data.meshes['Cylinder'].attributes['Fc'].data[1].color = (0.5, 0.6, 0.7, 0.8)
bpy.data.meshes['Cylinder'].attributes['Fc'].data[2].color = (0.9, 0.0, 0.25, 1.0)
bpy.data.meshes['Cylinder'].attributes['Bc'].data[0].color = (0.25, 0.5, 0.75, 1.0)
bpy.data.meshes['Cylinder'].attributes['Bc'].data[1].color = (1.0, 0.0, 0.5, 0.5)
bpy.data.meshes['Cylinder'].attributes['Bc'].data[30].color = (0.0, 0.5, 1.0, 0.0)
bpy.data.meshes['Cylinder'].attributes['Bc'].data[31].color = (0.75, 0.75, 0.25, 1.0)
bpy.data.objects['Cube'].select_set(True)
bpy.ops.object.mode_set(mode='EDIT')
bpy.ops.mesh.select_mode(type='FACE')
bpy.ops.frap.select_elements(type='FACE', indices=[0, 10, 11])
bpy.ops.frap.select_elements(type='FACE', indices=[4], object='Cube')
bpy.ops.mesh.colors_rotate()
bpy.data.meshes['Cylinder'].attributes.active_color = bpy.data.meshes['Cylinder'].attributes['Fc']
bpy.ops.mesh.colors_rotate(use_ccw=True)
bpy.ops.frap.select_elements(type='FACE', indices=[0, 1, 2, 3, 4, 5, 6, 7])
bpy.ops.mesh.colors_reverse()
bpy.data.meshes['Cylinder'].attributes.active_color = bpy.data.meshes['Cylinder'].attributes['Bc']
bpy.ops.mesh.colors_reverse()
bpy.ops.mesh.uvs_rotate()
