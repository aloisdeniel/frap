# WP 8.3.2: mesh.average_normals with every average_type on Suzannes with sharp edges and
# custom normals: CUSTOM_NORMAL (default), FACE_AREA (weight 50, then 75 with threshold 0.5),
# CORNER_ANGLE (weight 100, weight 1, weight 30 with threshold 0), on vertex and face
# selections; the fans walk the smooth edges only, so flat faces next to smooth edges join.
# golden: startup=factory compare=objects,context,mesh:Suzanne,mesh:Suzanne.001,mesh:Suzanne.002 tier=T1
import bpy
bpy.ops.mesh.primitive_monkey_add()
bpy.ops.object.shade_smooth()
bpy.ops.object.mode_set(mode='EDIT')
bpy.ops.mesh.select_all(action='SELECT')
bpy.ops.mesh.set_sharpness_by_angle(angle=0.9)
bpy.ops.mesh.select_mode(type='FACE')
bpy.ops.frap.select_elements(type='FACE', indices=[10, 11, 12, 13, 50, 51, 52, 200, 201, 202, 203, 300])
bpy.ops.mesh.set_normals_from_faces()
bpy.ops.mesh.select_mode(type='VERT')
bpy.ops.frap.select_elements(type='VERT', indices=[5, 6, 7, 8, 9, 10, 100, 101, 102, 250, 300, 301])
bpy.ops.mesh.average_normals()
bpy.ops.object.mode_set(mode='OBJECT')
bpy.ops.mesh.primitive_monkey_add(location=(3, 0, 0))
bpy.ops.object.shade_smooth()
bpy.ops.object.mode_set(mode='EDIT')
bpy.ops.mesh.select_all(action='SELECT')
bpy.ops.mesh.set_sharpness_by_angle(angle=0.9)
bpy.ops.mesh.select_mode(type='FACE')
bpy.ops.frap.select_elements(type='FACE', indices=[1, 2, 3, 4, 5, 6, 7, 8, 9, 60, 61, 62, 63, 64])
bpy.ops.mesh.faces_shade_flat()
bpy.ops.mesh.average_normals(average_type='FACE_AREA')
bpy.ops.frap.select_elements(type='FACE', indices=[100, 101, 102, 103, 104, 105, 400, 401, 402])
bpy.ops.mesh.average_normals(average_type='FACE_AREA', weight=75, threshold=0.5)
bpy.ops.object.mode_set(mode='OBJECT')
bpy.ops.mesh.primitive_monkey_add(location=(6, 0, 0))
bpy.ops.object.shade_smooth()
bpy.ops.object.mode_set(mode='EDIT')
bpy.ops.mesh.select_all(action='SELECT')
bpy.ops.mesh.set_sharpness_by_angle(angle=0.9)
bpy.ops.mesh.select_all(action='DESELECT')
bpy.ops.frap.select_elements(type='VERT', indices=[0, 5, 10, 15, 20, 25, 30, 35, 40, 45, 50, 55, 60, 65, 70, 75])
bpy.ops.mesh.average_normals(average_type='CORNER_ANGLE', weight=100)
bpy.ops.frap.select_elements(type='VERT', indices=[80, 87, 94, 101, 108, 115, 122, 129, 136, 143, 150, 157, 164, 171, 178, 185, 192, 199])
bpy.ops.mesh.average_normals(average_type='CORNER_ANGLE', weight=1)
bpy.ops.frap.select_elements(type='VERT', indices=[200, 211, 222, 233, 244, 255, 266, 277, 288, 299, 310, 321, 332, 343, 354, 365, 376, 387, 398])
bpy.ops.mesh.average_normals(average_type='CORNER_ANGLE', weight=30, threshold=0.0)
bpy.ops.frap.select_elements(type='VERT', indices=[400, 406, 412, 418, 424, 430, 436, 442, 448, 454, 460, 466, 472, 478, 484, 490, 496, 502])
bpy.ops.mesh.average_normals(average_type='FACE_AREA', weight=62, threshold=2.0)
