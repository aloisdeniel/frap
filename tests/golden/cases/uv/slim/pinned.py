# WP 8.1: SLIM with pins: the pins are soft constraints (penalty 1e101), the initial map is
# fitted to them (one pin: translation; two: similarity; three or more: least-squares rotation
# and scale), the mesh is scaled to the map's area, and the global scale invariance factor
# rescales the gradients every iteration. Ico spheres: their element order is stable (D-19).
# golden: startup=empty compare=objects,context,mesh:Icosphere,mesh:Icosphere.001,mesh:Icosphere.002 tier=T2 tol=1e-4
import bpy
bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=2)
bpy.ops.object.mode_set(mode='EDIT')
bpy.ops.mesh.select_all(action='SELECT')
bpy.ops.uv.seams_from_islands()
bpy.ops.uv.unwrap(method='CONFORMAL')
bpy.ops.mesh.select_all(action='DESELECT')
bpy.ops.frap.select_elements(type='VERT', indices=[3, 20, 31, 40])
bpy.ops.uv.pin()
bpy.ops.mesh.select_all(action='SELECT')
bpy.ops.uv.unwrap(method='MINIMUM_STRETCH', iterations=5)
bpy.ops.object.mode_set(mode='OBJECT')
bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=2, location=(3, 0, 0))
bpy.ops.object.mode_set(mode='EDIT')
bpy.ops.mesh.select_all(action='SELECT')
bpy.ops.uv.seams_from_islands()
bpy.ops.uv.unwrap(method='CONFORMAL')
bpy.ops.mesh.select_all(action='DESELECT')
bpy.ops.frap.select_elements(type='VERT', indices=[14, 33])
bpy.ops.uv.pin()
bpy.ops.mesh.select_all(action='SELECT')
bpy.ops.uv.unwrap(method='MINIMUM_STRETCH', iterations=5)
bpy.ops.object.mode_set(mode='OBJECT')
bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=2, location=(6, 0, 0))
bpy.ops.object.mode_set(mode='EDIT')
bpy.ops.mesh.select_all(action='SELECT')
bpy.ops.uv.seams_from_islands()
bpy.ops.uv.unwrap(method='CONFORMAL')
bpy.ops.mesh.select_all(action='DESELECT')
bpy.ops.frap.select_elements(type='VERT', indices=[33])
bpy.ops.uv.pin()
bpy.ops.mesh.select_all(action='SELECT')
bpy.ops.uv.unwrap(method='MINIMUM_STRETCH', iterations=5)
bpy.ops.object.mode_set(mode='OBJECT')
