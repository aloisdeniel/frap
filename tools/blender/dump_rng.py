"""Dump sequences of Blender's `BLI_rng` / `blender::RandomNumberGenerator` (WP 1.2, §21.4).

Runs INSIDE Blender:

    $BLENDER_BIN -b --factory-startup --python tools/blender/dump_rng.py -- \
        --out crates/frap-math/tests/data/blender_rng.rs

The generator is not exposed to Python, so the sequence is observed through two C operators
whose use of it is simple and documented in Blender's source (v5.2.4):

* `transform.vertex_random(offset=1, uniform=1, normal=0, seed=s)`
  (`editors/object/object_random.cc`, `object_rand_transverts`): `RandomNumberGenerator
  rng(seed)`; per selected vertex, in index order, one `get_float()` (the uniform factor, which
  is 1 here whatever it draws) and one `get_unit_float3()` (`z = 2 f - 1`, then
  `a = 2 pi f`, `x = r cos a`, `y = r sin a` with `r = sqrt(1 - z^2)`), added to the vertex.
  All vertices start at the origin, so each final position is exactly the unit vector drawn.
* `mesh.select_random(ratio=r, seed=s, action='SELECT')` (`editors/mesh/editmesh_select.cc`):
  `BLI_array_randomize(verts, n, seed)` (plain `BLI_rng_seed`, then `BLI_rng_shuffle_array`,
  `j = get_uint32() % n` from the last element down) and selects the first `int(n * ratio)`
  shuffled vertices.

The output is a Rust source fragment included by `crates/frap-math/tests/rng.rs`. Floats are
written with Python's `repr` of the f32 value widened to double, which converts back to the
same f32 exactly.
"""

import os
import sys

import bpy

N_VERTS = 48
SEEDS_VERTEX_RANDOM = [0, 1, 2, 7, 42, 1234, 9999, 10000]
SELECT_RANDOM = [(0, 0.5), (1, 0.5), (3, 0.25), (77, 0.75), (500, 0.33), (10000, 0.9)]
N_SELECT = 20


def args():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    out = None
    for i, a in enumerate(argv):
        if a == "--out":
            out = argv[i + 1]
    if out is None:
        raise SystemExit("usage: ... -- --out <file.rs>")
    return out


def fresh_object(name, n):
    for ob in list(bpy.data.objects):
        bpy.data.objects.remove(ob)
    me = bpy.data.meshes.new(name)
    me.from_pydata([(0.0, 0.0, 0.0)] * n, [], [])
    ob = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(ob)
    bpy.context.view_layer.objects.active = ob
    ob.select_set(True)
    return ob


def vertex_random(seed):
    ob = fresh_object("VR", N_VERTS)
    bpy.ops.object.mode_set(mode='EDIT')
    bpy.ops.mesh.select_mode(type='VERT')
    bpy.ops.mesh.select_all(action='SELECT')
    bpy.ops.transform.vertex_random(offset=1.0, uniform=1.0, normal=0.0, seed=seed)
    bpy.ops.object.mode_set(mode='OBJECT')
    return [tuple(v.co) for v in ob.data.vertices]


def select_random(seed, ratio):
    ob = fresh_object("SR", N_SELECT)
    bpy.ops.object.mode_set(mode='EDIT')
    bpy.ops.mesh.select_mode(type='VERT')
    bpy.ops.mesh.select_all(action='DESELECT')
    bpy.ops.mesh.select_random(ratio=ratio, seed=seed, action='SELECT')
    bpy.ops.object.mode_set(mode='OBJECT')
    return [v.index for v in ob.data.vertices if v.select]


def main():
    out = args()
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// @generated by tools/blender/dump_rng.py from " + bpy.app.version_string
        + " (" + bpy.app.build_hash.decode() + "). Do not edit.",
        "",
        "/// `transform.vertex_random(offset=1, uniform=1, normal=0, seed)` on "
        + str(N_VERTS) + " vertices at the origin: (seed, final positions).",
        "pub const VERTEX_RANDOM: &[(u32, &[[f32; 3]])] = &[",
    ]
    for seed in SEEDS_VERTEX_RANDOM:
        co = vertex_random(seed)
        body = ", ".join("[" + ", ".join(repr(c) + "_f32" for c in v) + "]" for v in co)
        lines.append("    (" + str(seed) + ", &[" + body + "]),")
    lines.append("];")
    lines.append("")
    lines.append("/// `mesh.select_random(ratio, seed, action='SELECT')` on " + str(N_SELECT)
                 + " vertices: (seed, ratio, selected vertex indices).")
    lines.append("pub const SELECT_RANDOM: &[(u32, f32, &[usize])] = &[")
    for seed, ratio in SELECT_RANDOM:
        sel = select_random(seed, ratio)
        lines.append("    (" + str(seed) + ", " + repr(ratio) + "_f32, &["
                     + ", ".join(str(i) for i in sel) + "]),")
    lines.append("];")
    lines.append("")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("dump_rng: wrote", out)


main()
